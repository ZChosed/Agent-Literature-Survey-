#!/usr/bin/env python3
"""
select_report_corpus.py -- fix which documents the report is built from.

Rule (decided 2026-10-06):
    * every agent include (I1-I4) in screening/final/document_list.csv
    * the 15 highest-ranked D1 (digital twin) includes, by corpus rank -- the
      position in candidates.csv, which corpus_build.py orders by seed-weighted
      score. Rank only; retrieval status plays NO part, so the DT subset is not
      shaped by which PDFs happened to download.

The proposal scopes the DT side as a ~15-paper comparison subset; screening
included 44 D1 papers, so 29 are left out by this rule and listed as such.

Outputs
-------
    corpus/report_corpus.csv            the selected documents, with retrieval
                                        status joined from document_corpus.csv
    corpus/manual_retrieval_report.csv  the subset of manual_retrieval_needed.csv
                                        that is in the report corpus -- the only
                                        PDFs a human needs to fetch
    manual_pdfs/RETRIEVE.md             the same list as a clickable checklist
                                        (DOI + Google Scholar link per paper),
                                        regenerated each run so it shows only
                                        what is still missing
    provenance.json -> report_corpus    counts and the rule
"""

from __future__ import annotations

import csv
import json
import os
from urllib.parse import quote_plus

N_DT = 15
DOC_LIST = "screening/final/document_list.csv"
DOC_CORPUS = "corpus/document_corpus.csv"
MANUAL = "corpus/manual_retrieval_needed.csv"
OUT = "corpus/report_corpus.csv"
OUT_MANUAL = "corpus/manual_retrieval_report.csv"
PROV = "corpus/provenance.json"
DROP_DIR = "manual_pdfs"
CHECKLIST = os.path.join(DROP_DIR, "RETRIEVE.md")


def write_checklist(rows: list[dict]) -> None:
    """Missing report-corpus papers as a Markdown checklist, agent then DT, by rank."""
    missing = [r for r in rows if r["retrieval_status"] != "ok"]
    os.makedirs(DROP_DIR, exist_ok=True)
    lines = [
        "# Papers to retrieve by hand",
        "",
        f"**{len(missing)} papers** of the {len(rows)}-document report corpus could not be "
        "downloaded automatically (open-access landing pages with no direct PDF link, or "
        "publisher bot blocks).",
        "",
        "**How:** download each PDF and drop it in this folder (`manual_pdfs/`). "
        "Any filename works: each PDF is matched to its paper by the title on its first "
        "pages. Then run:",
        "",
        "```bash",
        "python fetch_documents.py --manual-only   # match, validate, extract; no network",
        "python select_report_corpus.py            # refresh this checklist",
        "```",
        "",
        "A PDF that matches no paper, or two similar ones, is reported and left "
        "alone; rename it to the `paper_id` shown below to force the match. "
        "Matched PDFs still go through the same title-and-length check as a "
        "download, so a wrong file is rejected.",
        "",
        "This file is regenerated by `select_report_corpus.py`; edits to it are overwritten.",
        "",
    ]
    for role, heading in (("agent", "Agent papers"), ("dt", "Digital twin papers")):
        group = [r for r in missing if r["role"] == role]
        if not group:
            continue
        lines += [f"## {heading} ({len(group)})", "",
                  "| | # | Title | Year | Venue | DOI | Search | paper_id |",
                  "|---|---:|---|---|---|---|---|---|"]
        for i, r in enumerate(group, 1):
            title = r["title"].replace("|", "\\|")
            venue = (r["venue"] or "").replace("|", "\\|")
            doi = f"[{r['doi']}](https://doi.org/{r['doi']})" if r["doi"] else ""
            scholar = ("[Scholar](https://scholar.google.com/scholar?q="
                       + quote_plus('"' + r["title"] + '"') + ")")
            lines.append(f"| ☐ | {i} | {title} | {r['year']} | {venue} | {doi} | "
                         f"{scholar} | `{r['paper_id']}` |")
        lines.append("")
    with open(CHECKLIST, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def main() -> int:
    docs = list(csv.DictReader(open(DOC_LIST, encoding="utf-8")))
    fetched = {r["paper_id"]: r for r in csv.DictReader(open(DOC_CORPUS, encoding="utf-8"))}
    manual = list(csv.DictReader(open(MANUAL, encoding="utf-8")))

    agent = [r for r in docs if r["criterion_id"] in ("I1", "I2", "I3", "I4")]
    dt_all = sorted((r for r in docs if r["criterion_id"] == "D1"),
                    key=lambda r: int(r["rank"]))
    dt = dt_all[:N_DT]
    chosen = agent + dt
    ids = {r["paper_id"] for r in chosen}

    cols = ["paper_id", "doi", "title", "year", "venue", "rank", "role",
            "criterion_id", "selection_basis", "retrieval_status",
            "retrieval_source", "pages", "chars"]
    rows = []
    for r in sorted(chosen, key=lambda r: int(r["rank"])):
        f = fetched.get(r["paper_id"], {})
        is_dt = r["criterion_id"] == "D1"
        rows.append({
            "paper_id": r["paper_id"], "doi": r["doi"], "title": r["title"],
            "year": r["year"], "venue": r["venue"], "rank": r["rank"],
            "role": "dt" if is_dt else "agent", "criterion_id": r["criterion_id"],
            "selection_basis": (f"D1, top {N_DT} by corpus rank "
                                f"({dt.index(r) + 1} of {len(dt_all)})" if is_dt
                                else "agent include (all)"),
            "retrieval_status": f.get("status", "missing"),
            "retrieval_source": f.get("source", ""),
            "pages": f.get("pages", ""), "chars": f.get("chars", ""),
        })
    with open(OUT, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)

    man = [m for m in manual if m["paper_id"] in ids]
    with open(OUT_MANUAL, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(manual[0].keys()) if manual else ["paper_id"])
        w.writeheader()
        w.writerows(sorted(man, key=lambda m: (m.get("role", ""), m["paper_id"])))

    ok = lambda role: sum(1 for r in rows if r["role"] == role and r["retrieval_status"] == "ok")
    block = {
        "script": "select_report_corpus.py",
        "rule": (f"all agent includes (I1-I4) + top {N_DT} D1 includes by corpus "
                 f"rank; retrieval status not used in selection"),
        "agent": len(agent), "dt_selected": len(dt), "dt_available": len(dt_all),
        "dt_left_out": [r["paper_id"] for r in dt_all[N_DT:]],
        "dt_rank_cutoff": int(dt[-1]["rank"]) if dt else None,
        "retrieved": {"agent": ok("agent"), "dt": ok("dt")},
        "manual_needed": {"agent": sum(1 for m in man if m.get("role") == "agent"),
                          "dt": sum(1 for m in man if m.get("role") == "dt")},
        "outputs": {"report_corpus": OUT, "manual_retrieval": OUT_MANUAL},
    }
    prov = json.load(open(PROV, encoding="utf-8")) if os.path.exists(PROV) else {}
    prov["report_corpus"] = block
    with open(PROV, "w", encoding="utf-8") as fh:
        json.dump(prov, fh, indent=2)
        fh.write("\n")

    print(f"[select] {len(agent)} agent + {len(dt)} DT (of {len(dt_all)}; "
          f"rank cutoff {block['dt_rank_cutoff']}) = {len(rows)} documents")
    print(f"[select] retrieved: agent {block['retrieved']['agent']}/{len(agent)}, "
          f"DT {block['retrieved']['dt']}/{len(dt)}")
    print(f"[select] manual retrieval needed: {len(man)} "
          f"(agent {block['manual_needed']['agent']}, DT {block['manual_needed']['dt']})")
    write_checklist(rows)
    print(f"  -> {OUT}\n  -> {OUT_MANUAL}\n  -> {CHECKLIST}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
